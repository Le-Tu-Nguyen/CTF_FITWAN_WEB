PRAGMA foreign_keys=ON;
PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY, username TEXT NOT NULL UNIQUE COLLATE NOCASE,
 password TEXT NOT NULL, admin INTEGER NOT NULL DEFAULT 0 CHECK(admin IN(0,1))
);
CREATE TABLE IF NOT EXISTS contest (
 id INTEGER PRIMARY KEY CHECK(id=1), title TEXT NOT NULL,
 start INTEGER NOT NULL, end INTEGER NOT NULL CHECK(end>start)
);
CREATE TABLE IF NOT EXISTS challenges (
 id INTEGER PRIMARY KEY, title TEXT NOT NULL, category TEXT NOT NULL,
 description TEXT NOT NULL, hint TEXT NOT NULL DEFAULT '',
 points INTEGER NOT NULL CHECK(points>0), flag_hash TEXT NOT NULL,
 visible INTEGER NOT NULL DEFAULT 0 CHECK(visible IN(0,1))
);
CREATE TABLE IF NOT EXISTS submissions (
 id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
 challenge_id INTEGER NOT NULL REFERENCES challenges(id), correct INTEGER NOT NULL,
 at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS solves (
 id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
 challenge_id INTEGER NOT NULL REFERENCES challenges(id), points INTEGER NOT NULL,
 at INTEGER NOT NULL, UNIQUE(user_id,challenge_id)
);
CREATE TABLE IF NOT EXISTS announcements (id INTEGER PRIMARY KEY, body TEXT NOT NULL, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS throttle (key TEXT NOT NULL, at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS throttle_lookup ON throttle(key,at);
CREATE INDEX IF NOT EXISTS submissions_user ON submissions(user_id,id);